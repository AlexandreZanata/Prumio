// Rows generated by SQLDelight → domain models. The inverse direction lives in Writes.kt.

internal fun InboxItemRow.toModel() = InboxItem(
    id = InboxItemId(id),
    text = text,
    createdAt = created_at.toInstant(),
    updatedAt = updated_at.toInstant(),
)

internal fun TaskRow.toModel(reminders: List<Reminder> = emptyList()) = Task(
    reminders = reminders,
    id = TaskId(id),
    title = title,
    notes = notes,
    status = status.toEnum(TaskStatus.entries, "task.status"),
    dueDate = due_date?.toLocalDate(),
    dueTime = due_time?.toLocalTime(),
    recurrence = null,
    matterId = matter_id?.let(::MatterId),
    completedAt = completed_at?.toInstant(),
    dismissedAt = dismissed_at?.toInstant(),
    createdAt = created_at.toInstant(),
    updatedAt = updated_at.toInstant(),
)

internal fun AppointmentRow.toModel(reminders: List<Reminder> = emptyList()): Appointment {
    val timing = if (all_day == 1L) {
        AppointmentTiming.AllDay(startDate = start_date.toLocalDate(), endDate = end_date.toLocalDate())
    } else {
        AppointmentTiming.Timed(
            start = LocalDateTime(start_date.toLocalDate(), requireNotNull(start_time).toLocalTime()),
            end = end_time?.let { LocalDateTime(end_date.toLocalDate(), it.toLocalTime()) },
            timeZone = TimeZone.of(requireNotNull(time_zone)),
        )
    }
    return Appointment(
        reminders = reminders, id = AppointmentId(id),
        title = title,
        notes = notes,
        location = location,
        timing = timing,
        recurrence = null,
        matterId = matter_id?.let(::MatterId),
        createdAt = created_at.toInstant(),
        updatedAt = updated_at.toInstant(),
    )
}

internal fun MatterRow.toModel() = Matter(
    id = MatterId(id),
    title = title,
    description = description,
    status = status.toEnum(MatterStatus.entries, "matter.status"),
    waitingFor = waiting_for,
    followUpDate = follow_up_date?.toLocalDate(),
    followUpTime = follow_up_time?.toLocalTime(),
    resolvedAt = resolved_at?.toInstant(),
    lastActivityAt = last_activity_at.toInstant(),
    createdAt = created_at.toInstant(),
    updatedAt = updated_at.toInstant(),
)

internal fun MatterEntryRow.toModel() = MatterEntry(
    id = MatterEntryId(id),
    matterId = MatterId(matter_id),
    kind = kind.toEnum(MatterEntryKind.entries, "matter_entry.kind"),
    text = text,
    fromStatus = from_status?.toEnum(MatterStatus.entries, "matter_entry.from_status"),
    toStatus = to_status?.toEnum(MatterStatus.entries, "matter_entry.to_status"),
    taskId = task_id?.let(::TaskId),
    occurredOn = occurred_on.toLocalDate(),
    createdAt = created_at.toInstant(),
    updatedAt = updated_at.toInstant(),
)
